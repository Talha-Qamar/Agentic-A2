"""Regenerate docs/TOOLS.md from the committed MCP schema snapshot (one row per tool) + hand-written trust notes.

    python scripts/gen_tools_doc.py
"""
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
ALLOW = yaml.safe_load((ROOT / "agent/config.yaml").read_text())["mcp"]["allowlists"]
SNAP = json.loads((ROOT / "tests/contract/mcp_schema_snapshot.json").read_text())
AUTH = {
    "portfolio": "Bearer per-user JWT (in GigBid; persona from `sub`). Standalone/uvx: optional static bearer `PORTFOLIO_MCP_TOKEN`, stdio needs none",
    "marketplace": "Bearer per-user JWT minted by the API (5 min). Real sends also need an HMAC approval token minted only by the approval endpoint",
    "workspace": "Bearer per-user JWT minted by the API",
}
NOTES = {
    "submit_proposal": "write; dry_run default true; approval_token + idempotency_key required for a real submit",
    "send_message": "write; dry_run default true; approval_token + idempotency_key required for a real send",
    "create_proposal_draft": "write (draft only, nothing visible to the client); idempotent",
    "create_interview_hold": "write to the user's own calendar store; idempotent",
    "create_email_draft": "write a draft only (never sends); idempotent",
}


def rw(a):
    return "read" if a and a.get("readOnlyHint") else "write"


def ann(a):
    if not a:
        return "-"
    return ", ".join(k.replace("Hint", "") for k, v in sorted(a.items()) if v) or "none"


rows = []
for server in ("portfolio", "marketplace", "workspace"):
    for name, t in sorted(SNAP[server].items()):
        args = ", ".join(sorted(t["input"].get("properties", {})))
        rows.append(f"| `{name}` | {server} (ours) | {rw(t['annotations'])} | {ann(t['annotations'])} | {AUTH[server].split('.')[0]} | {args} | {NOTES.get(name, '')} |")

doc = f"""# MCP tools

Generated by `scripts/gen_tools_doc.py` from `tests/contract/mcp_schema_snapshot.json`, the snapshot that CI checks
against the running servers - so this table cannot drift from the code. Annotations are the MCP `ToolAnnotations`
hints each tool declares (`readOnly`, `destructive`, `idempotent`, `openWorld`).

## Servers we wrote

| server | transport | auth |
|---|---|---|
| portfolio | streamable HTTP `/mcp` and stdio (`uvx ... gigbid-portfolio-mcp`) | {AUTH['portfolio']} |
| marketplace | streamable HTTP `/mcp`; port in front of GigSim (`adapters/gigsim.py`) or the Upwork MCP (`adapters/upwork_live.py`) | {AUTH['marketplace']} |
| workspace | streamable HTTP `/mcp` | {AUTH['workspace']} |

Every marketplace call is appended to the audit log (user, tool, masked arguments, result status, trace id); the table
has an append-only trigger (`common/db.py`). A per-user token bucket keeps the agent below GigSim's 120 req/min limit.

## One row per tool

| tool | server | read/write | annotations | auth | arguments | notes |
|---|---|---|---|---|---|---|
""" + "\n".join(rows) + """

Per-agent allowlists (filtered by tool name in `agent/mcp_client.py`, from `agent/config.yaml` `mcp.allowlists`):

| agent | tools |
|---|---|
""" + "\n".join(f"| {a} | {', '.join(f'`{t}`' for t in ts)} |" for a, ts in ALLOW.items()) + """

Only the submitter (approval node) and liaison hold write tools, and the marketplace server rejects a real
`submit_proposal` / `send_message` without an approval token that only the human approval endpoint can mint.

## Third-party servers (not written by us)

| server | used for | trust rationale (one line) |
|---|---|---|
| **Upwork official MCP** (`upwork.com/ai/mcp`, OAuth 2.1, live mode only) | job search, job/client details, proposal drafts, rooms/messages | First-party server run by the marketplace itself under its own OAuth consent and ToS, so it can see nothing the freelancer's Upwork account cannot already see; GigBid still never auto-sends (approval token gate sits in our marketplace port, in front of it). |
| **GitHub MCP** (`@modelcontextprotocol/server-github@2025.4.8`, stdio; GitHub's own `github-mcp-server` is a drop-in via `GITHUB_MCP_COMMAND`) | B1 ingestion of repo READMEs and code (`rag/ingest/github_mcp.py`) | Reference server from the MCP project, version-pinned, run locally over stdio with a read-only fine-grained token (public repos need none) and only `get_file_contents` is called, so the worst case is reading public code. |

Upwork tool names are resolved at connect time through `mcp_servers/marketplace/adapters/upwork_tool_map.yaml`, so a
renamed Upwork tool is a YAML change, not a code change.
"""
(ROOT / "docs/TOOLS.md").write_text(doc)
print(f"wrote docs/TOOLS.md ({len(rows)} tools)")
